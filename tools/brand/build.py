HEADER = (
    "<!-- SPDX-License-Identifier: Apache-2.0 -->\n"
    "<!-- Generated by tools/brand/build.py from branding/src. Edit the masters, not this file. -->\n"
)


def _inner(path: Path) -> tuple[str, dict[str, str], tuple[float, float]]:
    """Body of a master SVG (without <svg>, <title> and <style>), its per-class rules and size."""
    text = path.read_text()
    view = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', text)
    if view is None:
        raise ValueError(f"{path}: no viewBox")
    rules = dict(re.findall(r"\.([a-z]+)\{([^}]*)\}", re.search(r"<style>(.*?)</style>", text, re.S).group(1)))
    body = re.sub(r"<!--.*?-->|<title>.*?</title>|<style>.*?</style>", "", text, flags=re.S)
    body = re.sub(r"^\s*<svg[^>]*>|</svg>\s*$", "", body.strip(), flags=re.S).strip()
    return body, rules, (float(view.group(1)), float(view.group(2)))


def _style(rules: dict[str, str], palette: dict[str, str]) -> str:
    """Geometry from the master (stroke widths, caps) plus colours from the palette."""
    out = []
    for name, rule in rules.items():
        kept = [d for d in rule.split(";") if d and d.split(":")[0] not in ("fill", "stroke")]
        colour = palette.get(name, "")
        out.append(f".{name}{{{';'.join([*colour.split(';'), *kept]).strip(';')}}}")
    return "".join(out)


def svg(width: float, height: float, title: str, style: str, body: str) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width:g} {height:g}" '
        f'width="{width:g}" height="{height:g}" role="img">\n{HEADER}<title>{title}</title>\n'
        f"<style>{style}</style>\n{body}\n</svg>\n"
    )


def build_svgs(out_dir: Path = SVG_OUT) -> dict[str, Path]:
    mark, mark_rules, _ = _inner(SRC / "mark.svg")
    small, small_rules, _ = _inner(SRC / "mark-small.svg")
    word, word_rules, (word_w, _) = _inner(SRC / "wordmark.svg")
    tag, tag_rules, (tag_w, _) = _inner(SRC / "tagline.svg")
    out_dir.mkdir(parents=True, exist_ok=True)
    made: dict[str, Path] = {}

    def write(name: str, content: str) -> None:
        path = out_dir / f"{name}.svg"
        path.write_text(content)
        made[name] = path

    for variant, palette in PALETTES.items():
        tile_rule = {"tile": "stroke-width:2"}
        # Marks on a transparent background.
        write(f"mark-{variant}", svg(256, 256, "MeshBeacon", _style(mark_rules, palette), mark))
        write(f"mark-small-{variant}", svg(256, 256, "MeshBeacon", _style(small_rules, palette), small))
        # App icon: the mark on a rounded tile (works on light and dark surfaces alike).
        tile = '<rect class="tile" x="1" y="1" width="254" height="254" rx="56"/>'
        for name, body, rules, fit in (
            ("icon", mark, mark_rules, "translate(20.5 26) scale(0.84)"),
            ("icon-small", small, small_rules, "translate(10 12) scale(0.92)"),  # fills more of a tiny tile
        ):
            inner = f'{tile}\n<g transform="{fit}">{body}</g>'
            write(f"{name}-{variant}", svg(256, 256, "MeshBeacon", _style({**rules, **tile_rule}, palette), inner))
        # Horizontal logo: mark + wordmark, cap height 92 on a 256 mark, vertically centred.
        scale = 92 / 72.75
        word_x, word_y = 296, (256 - 92) / 2 - (96.88 - 72.75) * scale
        width = word_x + word_w * scale
        horizontal = f'<g>{mark}</g>\n<g transform="translate({word_x:g} {word_y:.2f}) scale({scale:.4f})">{word}</g>'
        rules = {**mark_rules, **word_rules}
        write(f"logo-horizontal-{variant}", svg(width, 256, "MeshBeacon", _style(rules, palette), horizontal))
        # Badge: the horizontal logo on its own tile, 2.5 : 1 (Home Assistant's app logo.png), so it
        # stays legible on light and dark app pages alike.
        badge_w = width + 120
        badge_h = badge_w / 2.5
        badge = (
            f'<rect class="tile" x="1" y="1" width="{badge_w - 2:g}" height="{badge_h - 2:.1f}" rx="72"/>\n'
            f'<g transform="translate(60 {(badge_h - 256) / 2:.1f})">{horizontal}</g>'
        )
        write(
            f"logo-badge-{variant}",
            svg(badge_w, badge_h, "MeshBeacon", _style({**rules, **tile_rule}, palette), badge),
        )
        # Full logo: the horizontal logo plus the tagline under the wordmark, same width.
        tag_scale = word_w * scale / tag_w
        top = (256 - (92 + 34 + 72.75 * tag_scale)) / 2
        word_y2 = top - (96.88 - 72.75) * scale
        tag_y = top + 92 + 34 - (96.88 - 72.75) * tag_scale
        full = (
            f"<g>{mark}</g>\n"
            f'<g transform="translate({word_x:g} {word_y2:.2f}) scale({scale:.4f})">{word}</g>\n'
            f'<g transform="translate({word_x:g} {tag_y:.2f}) scale({tag_scale:.4f})">{tag}</g>'
        )
        rules = {**mark_rules, **word_rules, **tag_rules}
        write(
            f"logo-full-{variant}",
            svg(width, 256, "MeshBeacon: Decentralised connectivity for your home", _style(rules, palette), full),
        )
    # Favicon source: the small icon on the dark tile (legible on any browser tab).
    shutil.copyfile(made["icon-small-dark"], out_dir / "favicon.svg")
    made["favicon"] = out_dir / "favicon.svg"
    return made


def build_mark_module(out: Path | None = None) -> Path:
    """The marks as data for the interface (no markup is parsed in the page): element name,
    class and geometry. Colours come from the page's design tokens, so the mark follows the theme."""
    marks = {}
    for key, name in (("full", "mark.svg"), ("small", "mark-small.svg")):
        root = ET.parse(SRC / name).getroot()
        strokes = dict(re.findall(r"\.([a-z]+)\{[^}]*?stroke-width:([\d.]+)", root.findtext("{*}style") or ""))
        shapes = []
        for el in root:
            tag = el.tag.split("}")[1]
            if tag in ("path", "rect", "circle"):
                attrs = {k: v for k, v in el.attrib.items() if k != "class"}
                cls = el.get("class", "")
                if cls in strokes:
                    attrs["stroke-width"] = strokes[cls]
                shapes.append([tag, cls, attrs])
        marks[key] = shapes
    out = out or FRONTEND / "brand-mark.js"
    out.write_text(
        "// SPDX-License-Identifier: Apache-2.0\n"
        "// Generated by tools/brand/build.py from branding/src/mark*.svg. Do not edit by hand.\n"
        "// [element, class, attributes]; classes are coloured by the page's design tokens.\n"
        f"export const MARKS = Object.freeze({json.dumps(marks, separators=(',', ':'))});\n"
    )
    return out


def png_jobs(svgs: dict[str, Path]) -> list[dict[str, object]]:
    j: list[dict[str, object]] = []

    def job(src: str, out: Path, width: int, height: int | None = None, trim: bool = False) -> None:
        j.append({"svg": str(svgs[src]), "png": str(out), "width": width, "height": height or width, "trim": trim})

    for variant in PALETTES:
        for size in (512, 256, 128):
            job(f"icon-{variant}", PNG_OUT / f"icon-{variant}-{size}.png", size)
        job(f"logo-horizontal-{variant}", PNG_OUT / f"logo-horizontal-{variant}.png", 0, 128, trim=True)
        job(f"logo-full-{variant}", PNG_OUT / f"logo-full-{variant}.png", 0, 256, trim=True)
    job("icon-small-dark", PNG_OUT / "favicon-16.png", 16)
    job("icon-small-dark", PNG_OUT / "favicon-32.png", 32)
    job("icon-dark", PNG_OUT / "favicon-64.png", 64)
    # Home Assistant app store and app page (Supervisor): icon.png square, 128 x 128 recommended;
    # logo.png about 250 x 100. No dark variants are documented for apps, so the tile is used.
    job("icon-dark", APP / "icon.png", 128)
    job("logo-badge-dark", APP / "logo.png", 250, 100)
    job("logo-badge-dark", PNG_OUT / "logo-badge-dark.png", 500, 200)
    # Optional integration, local brand images (Home Assistant 2026.3+, components/brands):
    # icon 256 (@2x 512), logo shortest side 128 (@2x 256), transparent and trimmed.
    for prefix, variant in (("", "light"), ("dark_", "dark")):
        job(f"mark-{variant}", BRAND / f"{prefix}icon.png", 256, trim=True)
        job(f"mark-{variant}", BRAND / f"{prefix}icon@2x.png", 512, trim=True)
        job(f"logo-horizontal-{variant}", BRAND / f"{prefix}logo.png", 0, 128, trim=True)
        job(f"logo-horizontal-{variant}", BRAND / f"{prefix}logo@2x.png", 0, 256, trim=True)
    return j


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--svg-only", action="store_true")
    parser.add_argument("--check", action="store_true", help="fail if generated SVGs or mark data are stale")
    args = parser.parse_args(argv)
    if args.check:
        import tempfile

        with tempfile.TemporaryDirectory() as tmp:
            fresh = build_svgs(Path(tmp))
            stale = [n for n, p in fresh.items() if p.read_text() != (SVG_OUT / p.name).read_text()]
            mark = build_mark_module(Path(tmp) / "brand-mark.js").read_text()
            if mark != (FRONTEND / "brand-mark.js").read_text():
                stale.append("brand-mark.js")
        if stale:
            print("stale brand assets (run tools/brand/build.py):", ", ".join(sorted(stale)))
            return 1
        print("brand assets up to date")
        return 0
    svgs = build_svgs()
    print(f"{len(svgs)} SVG variants in {SVG_OUT.relative_to(ROOT)}")
    print(f"interface mark data: {build_mark_module().relative_to(ROOT)}")
    if args.svg_only:
        return 0
    jobs = png_jobs(svgs)
    for item in jobs:
        Path(str(item["png"])).parent.mkdir(parents=True, exist_ok=True)
    manifest = PNG_OUT / ".render.json"
    manifest.write_text(json.dumps(jobs))
    try:
        subprocess.run(["node", str(Path(__file__).with_name("render.mjs")), str(manifest)], check=True)
    finally:
        manifest.unlink(missing_ok=True)
    try:  # optional optimisation: flat artwork quantises to a 256-colour palette without visible loss
        from PIL import Image

        for item in jobs:
            path = Path(str(item["png"]))
            image = Image.open(path).convert("RGBA")
            image.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).save(
                path, optimize=True
            )
    except ImportError:
        print("Pillow not installed: PNGs left unoptimised")
    print(f"{len(jobs)} PNGs rendered")
    return 0


if __name__ == "__main__":
    sys.exit(main())
